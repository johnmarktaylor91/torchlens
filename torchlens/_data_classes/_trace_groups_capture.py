"""Capture-side concern groups of a ``Trace``: ``trace.options``, ``trace.source``, ``trace.health``.

Each group is a light read-only view over its Trace; the facts it
exposes are computed by the Trace's private implementation members.
``trace.cost``, ``trace.graph``, ``trace.autograd`` and ``trace.provenance``
live in ``_trace_groups``.
"""

from __future__ import annotations

from typing import Any

from ._trace_groups import _TraceGroup


class TraceSettings(_TraceGroup):
    """The capture options this Trace ran with (the stored snapshot).

    Examples
    --------
    >>> trace = tl.trace(model, x, capture=tl.options.CaptureOptions(backward_ready=True))
    >>> type(trace.options).__name__, trace.options.backward_ready
    ('TraceSettings', True)
    """

    __slots__ = ()

    @property
    def source_context_lines(self) -> Any:
        """Number of source-context lines saved per op (stored as ``num_context_lines`` in v11)."""

        return self._trace.num_context_lines

    # --- v11 stored leaves (generated by groupmod.py views; do not edit by hand) ---
    @property
    def activation_transform(self) -> Any:
        """callable applied to saved forward outputs before storage."""

        return self._trace._options_activation_transform

    @property
    def backward_ready(self) -> Any:
        """backward machinery prepared at capture. `inference_only`: captured under `torch.no_grad()`."""

        return self._trace._options_backward_ready

    @property
    def chunk_size(self) -> Any:
        """chunked-append provenance."""

        return self._trace._options_chunk_size

    @property
    def detach_saved_activations(self) -> Any:
        """saved tensors detached from autograd."""

        return self._trace._options_detach_saved_activations

    @property
    def emit_nvtx(self) -> Any:
        """capture toggles."""

        return self._trace._options_emit_nvtx

    @property
    def grad_transform(self) -> Any:
        """callable applied to saved gradients."""

        return self._trace._options_grad_transform

    @property
    def grouping(self) -> Any:
        """`"structural"` (default), `"strict_shapes"`/`"fold_sites"` (reserved, refuse typed pre-ratification)."""

        return self._trace._options_grouping

    @property
    def grouping_policy(self) -> Any:
        """Stamp of the layer-grouping policy that produced the layers."""

        return self._trace._options_grouping_policy

    @property
    def inference_only(self) -> Any:
        """Whether the capture ran under inference mode."""

        return self._trace._options_inference_only

    @property
    def input_transform(self) -> Any:
        """portable `repr()` of the input / gradient transform callables. (`gradient_transform` ruled v12; not yet shipped -- the field itself is still `grad_transform`.)"""

        return self._trace._options_input_transform

    @property
    def jax_static_argnums(self) -> Any:
        """Static argument positions passed to the JAX capture."""

        return self._trace._options_jax_static_argnums

    @property
    def keep_orphans(self) -> Any:
        """whether orphan island Ops are retained."""

        return self._trace._options_keep_orphans

    @property
    def mark_layer_depths(self) -> Any:
        """capture toggles."""

        return self._trace._options_mark_layer_depths

    @property
    def mode(self) -> Any:
        """`"exhaustive"`, `"fast"`, or `"predicate"` (the capture-mechanism word)."""

        return self._trace._options_mode

    @property
    def module_identity_mode(self) -> Any:
        """how modules are identified — `"torch_module"`, `"pytree_module"`, `"function_root"`, `"object_module"`."""

        return self._trace._options_module_identity_mode

    @property
    def on_nonfinite(self) -> Any:
        """capture toggles."""

        return self._trace._options_on_nonfinite

    @property
    def output_device(self) -> Any:
        """device where saved outputs are placed. `save_mode`: tensor retention mode (`"copy"`, `"reference"`, `"view"`, `"cpu_async"`)."""

        return self._trace._options_output_device

    @property
    def recurrence_detection(self) -> Any:
        """loop/recurrence detection on/off."""

        return self._trace._options_recurrence_detection

    @property
    def save(self) -> Any:
        """The save selector the capture ran with."""

        return self._trace._options_save

    @property
    def save_arg_templates(self) -> Any:
        """deep-copied Op arguments / structural arg templates."""

        return self._trace._options_save_arg_templates

    @property
    def save_args(self) -> Any:
        """deep-copied Op arguments / structural arg templates."""

        return self._trace._options_save_args

    @property
    def save_grads(self) -> Any:
        """whether operation gradients are retained after backward."""

        return self._trace._options_save_grads

    @property
    def save_mode(self) -> Any:
        """How saved activations were retained (``copy`` or ``reference``)."""

        return self._trace._options_save_mode

    @property
    def save_raw_activations(self) -> Any:
        """whether raw untransformed tensors are saved."""

        return self._trace._options_save_raw_activations

    @property
    def save_raw_grads(self) -> Any:
        """whether raw untransformed tensors are saved."""

        return self._trace._options_save_raw_grads

    @property
    def save_raw_input(self) -> Any:
        """raw-I/O save policy + batch rendering policy for visualization."""

        return self._trace._options_save_raw_input

    @property
    def save_rng(self) -> Any:
        """RNG snapshots. `save_code_context`: source-code context."""

        return self._trace._options_save_rng

    @property
    def save_source_context(self) -> Any:
        """Whether source-context frames were saved for each op."""

        return self._trace._options_save_source_context

    @property
    def save_transformed_output(self) -> Any:
        """raw-I/O save policy + batch rendering policy for visualization."""

        return self._trace._options_save_transformed_output

    @property
    def seed(self) -> Any:
        """RNG seed applied for capture, if any."""

        return self._trace._options_seed

    @property
    def structure_only(self) -> Any:
        """see Capture products above."""

        return self._trace._options_structure_only

    @property
    def verbose(self) -> Any:
        """capture toggles."""

        return self._trace._options_verbose

    # --- end v11 stored leaves ---


class TraceSource(_TraceGroup):
    """Source facts of the traced model class: locations, signatures, docstrings.

    Examples
    --------
    >>> source = tl.trace(model, x).source
    >>> type(source).__name__, source.class_name
    ('TraceSource', 'Sequential')

    """

    __slots__ = ()

    @property
    def class_location(self) -> Any:
        """Combined model class source location."""

        return self._trace._source_class_location

    @property
    def cls(self) -> Any:
        """Return the live source model class when the model is still alive."""

        return self._trace._source_cls

    @property
    def forward_location(self) -> Any:
        """Combined forward source location."""

        return self._trace._source_forward_location

    @property
    def init_location(self) -> Any:
        """Combined model ``__init__`` source location."""

        return self._trace._source_init_location

    # --- v11 stored leaves (generated by groupmod.py views; do not edit by hand) ---
    @property
    def class_docstring(self) -> Any:
        """model class location and docs."""

        return self._trace._source_class_docstring

    @property
    def class_file(self) -> Any:
        """model class location and docs."""

        return self._trace._source_class_file

    @property
    def class_line(self) -> Any:
        """model class location and docs."""

        return self._trace._source_class_line

    @property
    def class_name(self) -> Any:
        """short Python class name of the source model."""

        return self._trace._source_class_name

    @property
    def class_qualname(self) -> Any:
        """fully qualified class name; useful for run verification."""

        return self._trace._source_class_qualname

    @property
    def forward_docstring(self) -> Any:
        """`forward()` info."""

        return self._trace._source_forward_docstring

    @property
    def forward_file(self) -> Any:
        """`forward()` info."""

        return self._trace._source_forward_file

    @property
    def forward_line(self) -> Any:
        """`forward()` info."""

        return self._trace._source_forward_line

    @property
    def forward_signature(self) -> Any:
        """`forward()` info."""

        return self._trace._source_forward_signature

    @property
    def frames(self) -> Any:
        """Python call-stack frames at capture time (`list[FuncCallLocation]`)."""

        return self._trace._source_frames

    @property
    def init_docstring(self) -> Any:
        """`__init__` info."""

        return self._trace._source_init_docstring

    @property
    def init_file(self) -> Any:
        """`__init__` info."""

        return self._trace._source_init_file

    @property
    def init_line(self) -> Any:
        """`__init__` info."""

        return self._trace._source_init_line

    @property
    def init_signature(self) -> Any:
        """`__init__` info."""

        return self._trace._source_init_signature

    @property
    def snapshots(self) -> Any:
        """Source snapshots taken for the traced model."""

        return self._trace._source_snapshots

    # --- end v11 stored leaves ---


class TraceHealth(_TraceGroup):
    """Honesty diagnostics of the capture: witness and escape-detector facts.

    Examples
    --------
    >>> health = tl.trace(model, x).health
    >>> type(health).__name__, isinstance(health.num_escape_detector_events, int)
    ('TraceHealth', True)

    """

    __slots__ = ()

    # --- v11 stored leaves (generated by groupmod.py views; do not edit by hand) ---
    @property
    def completeness_callback_ns(self) -> Any:
        """Time spent in the completeness-witness callback, in nanoseconds."""

        return self._trace._health_completeness_callback_ns

    @property
    def completeness_decompositions(self) -> Any:
        """Completeness-witness decompositions of the captured op stream."""

        return self._trace._health_completeness_decompositions

    @property
    def completeness_mode(self) -> Any:
        """Mode the completeness witness ran in."""

        return self._trace._health_completeness_mode

    @property
    def completeness_verified(self) -> Any:
        """Whether the completeness witness verified the capture."""

        return self._trace._health_completeness_verified

    @property
    def escape_detector_callback_ns(self) -> Any:
        """Time spent in the escape-detector callback, in nanoseconds."""

        return self._trace._health_escape_detector_callback_ns

    @property
    def escape_detector_mode(self) -> Any:
        """Mode the escape detector ran in."""

        return self._trace._health_escape_detector_mode

    @property
    def escape_detector_verified(self) -> Any:
        """Whether the escape detector verified the capture."""

        return self._trace._health_escape_detector_verified

    @property
    def num_accounted_witness_events(self) -> Any:
        """Number of witness events accounted for by captured ops."""

        return self._trace._health_num_accounted_witness_events

    @property
    def num_escape_detector_events(self) -> Any:
        """Number of escape-detector events observed."""

        return self._trace._health_num_escape_detector_events

    @property
    def num_expected_opaque_witness_events(self) -> Any:
        """Number of witness events expected to be opaque."""

        return self._trace._health_num_expected_opaque_witness_events

    @property
    def num_unaccounted_witness_events(self) -> Any:
        """Number of witness events no captured op accounts for."""

        return self._trace._health_num_unaccounted_witness_events

    @property
    def num_witness_events(self) -> Any:
        """Number of completeness-witness events observed."""

        return self._trace._health_num_witness_events

    # --- end v11 stored leaves ---
