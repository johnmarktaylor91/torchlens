def _running_dot_version() -> str:
    """Return the running ``dot`` C-binary version string (or ``"absent"``)."""

    import shutil
    import subprocess

    dot = shutil.which("dot")
    if dot is None:
        return "absent"
    completed = subprocess.run([dot, "-V"], capture_output=True, text=True, timeout=30)
    # `dot -V` prints e.g. "dot - graphviz version 2.43.0 (0)" on stderr.
    match = re.search(r"graphviz version (\S+)", completed.stderr + completed.stdout)
    return match.group(1) if match else "unparseable"


def _canonical_bundle() -> tl.Bundle:
    """Return the canonical Phase 9 clean-vs-ablated ResNet-18 bundle.

    Returns
    -------
    tl.Bundle
        Bundle with ``clean`` and ``ablated`` members.
    """

    torchvision_models = pytest.importorskip("torchvision.models")
    torch.manual_seed(0)
    model = torchvision_models.resnet18(weights=None).eval()
    x = torch.randn(1, 3, 224, 224)
    trace = tl.trace(model, x, capture=tl.options.CaptureOptions(replayable=True))
    ablated_log = trace.fork("ablated")
    with pytest.warns(MultiMatchWarning):
        ablated_log.do(
            tl.module("layer1.0.relu"),
            tl.zero_ablate(),
            intervention=tl.options.InterventionOptions(confirm_mutation=True),
        )
    return tl.Bundle({"clean": trace, "ablated": ablated_log}, baseline="clean")


def _normalize_svg(svg: str) -> bytes:
    """Normalize semantic SVG text before byte comparison.

    Parameters
    ----------
    svg:
        Raw SVG text.

    Returns
    -------
    bytes
        Normalized UTF-8 payload.
    """

    normalized = re.sub(r'id="node\d+"', 'id="node"', svg)
    normalized = re.sub(r'id="edge\d+"', 'id="edge"', normalized)
    normalized = re.sub(r"<!-- Generated by graphviz version .*?-->", "", normalized, flags=re.S)
    normalized = re.sub(r"<!-- Title: .*?-->", "", normalized)
    normalized = re.sub(r"<!-- Pages: .*?-->", "", normalized)
    normalized = re.sub(r"\s+", " ", normalized).strip()
    return normalized.encode("utf-8")


def _rasterize(svg_path: Path) -> np.ndarray[Any, np.dtype[np.uint8]]:
    """Rasterize an SVG file to an RGB pixel array.

    Parameters
    ----------
    svg_path:
        SVG file path.

    Returns
    -------
    np.ndarray[Any, np.dtype[np.uint8]]
        RGB pixel data.
    """

    cairosvg = pytest.importorskip("cairosvg")
    from PIL import Image as pillow_image

    png_bytes = cairosvg.svg2png(url=str(svg_path), output_width=1200, output_height=800)
    image = pillow_image.open(BytesIO(png_bytes)).convert("RGB")
    return np.asarray(image, dtype=np.uint8)


def _pixel_similarity(candidate_path: Path, reference_path: Path) -> float:
    """Return a normalized pixel similarity score for two SVG files.

    Parameters
    ----------
    candidate_path:
        Candidate SVG path.
    reference_path:
        Reference SVG path.

    Returns
    -------
    float
        Similarity in ``[0, 1]``.
    """

    candidate = _rasterize(candidate_path).astype(np.float32)
    reference = _rasterize(reference_path).astype(np.float32)
    if candidate.shape != reference.shape:
        return 0.0
    mean_abs = float(np.mean(np.abs(candidate - reference)))
    return max(0.0, 1.0 - (mean_abs / 255.0))


@pytest.mark.xfail(
    strict=False,
    reason=(
        "OPEN root-cause, relayed to the viz/bundle lane (fixwave-3 testinfra-r4, "
        "2026-08-15): bundle-diff delta labels changed between 12797edc (golden "
        "authored there and reproduces there: 30x delta=1, 2x delta=1.25, no "
        "delta=0) and 41218e2d (16 labels now read delta=0). The divergence was "
        "invisible until this wave because the byte mismatch degraded to a "
        "cairosvg SKIP (b10 R78-4). Adjudicate which labeling is semantically "
        "correct, then rebaseline the golden and retire this xfail TOGETHER. "
        "Non-strict: a cairosvg-equipped box may pass via pixel exoneration."
    ),
)
def test_bundle_diff_canonical_resnet_snapshot(tmp_path: Path) -> None:
    """Canonical hero demo matches normalized SVG or image threshold."""

    bundle = _canonical_bundle()
    outpath = tmp_path / "bundle_diff_clean_vs_zero_relu"
    dot_source = bundle.draw(graph="diff", path=str(outpath)).dot
    candidate_svg = outpath.with_suffix(".svg")

    assert dot_source.startswith("// TorchLens bundle diff")
    assert candidate_svg.exists()
    svg_text = candidate_svg.read_text(encoding="utf-8")
    assert "aria-label=" in svg_text
    assert "clean vs ablated" in svg_text
    assert "zero_ablate(layer1.0.relu)" not in svg_text
    assert len(bundle._aligned_pairs("clean", "ablated")) > 0

    candidate_normalized = _normalize_svg(svg_text)
    reference_normalized = _normalize_svg(GOLDEN_SVG.read_text(encoding="utf-8"))
    if candidate_normalized == reference_normalized:
        return

    # Byte divergence: build the renderer-version explanation BEFORE deciding
    # the verdict, so a distro graphviz upgrade reds with its cause named
    # (b10 R78-3) instead of an unexplainable byte diff.
    recorded_dot = (
        DOT_VERSION_MARKER.read_text(encoding="utf-8").strip()
        if DOT_VERSION_MARKER.exists()
        else "unrecorded"
    )
    running_dot = _running_dot_version()
    context = (
        f"golden emitted by dot {recorded_dot}, this environment runs dot {running_dot} — "
        + (
            "renderer versions MATCH, so this is a real TorchLens render change"
            if recorded_dot == running_dot
            else "renderer versions DIFFER; rebaseline deliberately (update the golden AND "
            "tests/snapshots/ENV-graphviz-dot together) if the new output is correct"
        )
    )
    # The pixel-similarity layer EXONERATES benign byte drift; it must never
    # convert a real regression into a skip (b10 R78-4: cairosvg is installed
    # nowhere, so the mid-test importorskip made every byte regression green-
    # adjacent on every environment that exists).
    import importlib.util

    if importlib.util.find_spec("cairosvg") is None:
        pytest.fail(
            "bundle-diff SVG bytes diverged from the committed golden and cairosvg is "
            f"unavailable to run the pixel-similarity exoneration. {context}"
        )
    similarity = _pixel_similarity(candidate_svg, GOLDEN_SVG)
    assert similarity >= 0.95, f"pixel similarity {similarity:.3f} < 0.95. {context}"


def test_bundle_diff_caption_uses_selected_members(tmp_path: Path) -> None:
    """Bundle diff captions should describe the actual rendered comparison."""

    torch.manual_seed(0)
    model = torch.nn.Linear(3, 2).eval()
    left = tl.trace(model, torch.randn(1, 3))
    right = left.fork("patched")
    bundle = tl.Bundle({"base": left, "patched": right}, baseline="base")

    outpath = tmp_path / "member_caption"
    dot_source = bundle.draw(
        graph="diff",
        members=("base", "patched"),
        path=str(outpath),
    ).dot
    svg_text = outpath.with_suffix(".svg").read_text(encoding="utf-8")

    assert "base vs patched" in dot_source
    assert "columns: base, patched" in dot_source
    assert "layer1.0.relu" not in dot_source
    assert "top: clean, bottom: ablated" not in dot_source
    assert "base versus patched" in svg_text


def test_bundle_diff_uses_each_members_own_delta() -> None:
    """Left and right clusters show their own deltas from a custom baseline."""

    left_layer = SimpleNamespace(layer_label="left_1", func_name="op", parents=[], shape=None)
    right_layer = SimpleNamespace(layer_label="right_1", func_name="op", parents=[], shape=None)
    bundle = {
        "baseline": SimpleNamespace(_layer_list=[]),
        "left": SimpleNamespace(_layer_list=[left_layer]),
        "right": SimpleNamespace(_layer_list=[right_layer]),
    }

    dot = _build_dot(
        pairs=[(left_layer, right_layer)],
        bundle=bundle,
        left_name="left",
        right_name="right",
        metric_name="relative_l2",
        tensor_field="out",
        delta_map={"node_1": {"baseline": 0.0, "left": 1.25, "right": 5.5}},
        layer_to_node={"left_1": "node_1", "right_1": "node_1"},
        theme_name="paper",
        include_unmatched=False,
    )
    source = dot.source

    assert re.search('clean_left_1 \\[.*label="left_1\nop\ndelta=1.25"', source, re.S)
    assert re.search('intervention_right_1 \\[.*label="right_1\nop\ndelta=5.5"', source, re.S)


def test_bundle_diff_pair_selection_considers_left_delta() -> None:
    """Top-pair selection uses both members' own baseline deltas."""

    left_high = SimpleNamespace(layer_label="left_high")
    right_low = SimpleNamespace(layer_label="right_low")
    left_low = SimpleNamespace(layer_label="left_low")
    right_mid = SimpleNamespace(layer_label="right_mid")

    selected = _select_pairs(
        [(left_high, right_low), (left_low, right_mid)],
        names=("left", "right"),
        delta_map={
            "node_high": {"left": 9.0, "right": 0.0},
            "node_mid": {"left": 0.0, "right": 5.0},
        },
        layer_to_node={
            "left_high": "node_high",
            "right_low": "node_high",
            "left_low": "node_mid",
            "right_mid": "node_mid",
        },
        max_pairs=1,
    )

    assert selected == [(left_high, right_low)]


def _diff_bundle_with_marked_column() -> tl.Bundle:
    """A clean/patched bundle whose patched column carries non-zero deltas."""

    torch.manual_seed(0)
    model = torch.nn.Sequential(
        torch.nn.Linear(4, 6), torch.nn.ReLU(), torch.nn.Linear(6, 6), torch.nn.Tanh()
    ).eval()
    clean = tl.trace(model, torch.randn(1, 4), capture=tl.options.CaptureOptions(replayable=True))
    patched = clean.fork("patched").do(
        tl.module("1"),
        tl.scale(0.5),
        intervention=tl.options.InterventionOptions(engine="replay", confirm_mutation=True),
    )
    return tl.Bundle({"clean": clean, "patched": patched}, baseline="clean")


def test_bundle_diff_dot_keeps_each_side_in_its_own_column_cluster() -> None:
    """DOT source: one global ranking, so pair rank constraints never empty the side clusters.

    Runs without Graphviz. The pair alignment emits ``rank=same`` subgraphs at
    the root; without ``newrank=true`` dot deletes every paired node from its
    side cluster and drops both clusters, which drew the white baseline column
    as an unlabeled duplicate beside the marked one.
    """

    left_layers = [
        SimpleNamespace(layer_label=f"op_{i}", func_name="op", parents=[f"op_{i - 1}"], shape=None)
        for i in range(3)
    ]
    right_layers = [
        SimpleNamespace(layer_label=f"op_{i}", func_name="op", parents=[f"op_{i - 1}"], shape=None)
        for i in range(3)
    ]
    bundle = {
        "clean": SimpleNamespace(_layer_list=left_layers),
        "patched": SimpleNamespace(_layer_list=right_layers),
    }
    dot = _build_dot(
        pairs=list(zip(left_layers, right_layers, strict=True)),
        bundle=bundle,
        left_name="clean",
        right_name="patched",
        metric_name="relative_l2",
        tensor_field="out",
        delta_map={f"op_{i}": {"clean": 0.0, "patched": float(i + 1)} for i in range(3)},
        layer_to_node={f"op_{i}": f"op_{i}" for i in range(3)},
        theme_name="paper",
        include_unmatched=False,
    )
    source = dot.source
    assert re.search(r"graph \[[^\]]*\bnewrank=true\b", source)
    assert source.count("subgraph cluster_clean {") == 1
    assert source.count("subgraph cluster_intervention {") == 1
    # Each side's nodes are declared exactly once, inside that side's cluster.
    for side in ("clean", "intervention"):
        body = source.split(f"subgraph cluster_{side} {{", 1)[1].split("\n\t}", 1)[0]
        for i in range(3):
            assert f"\t{side}_op_{i} [label=" in body
            assert source.count(f"\t{side}_op_{i} [label=") == 1


def test_bundle_diff_render_draws_two_titled_columns(tmp_path: Path) -> None:
    """Rendered SVG: each member is one framed, titled column holding only its own nodes."""

    import shutil

    if shutil.which("dot") is None:
        pytest.skip("Graphviz dot is not installed; the DOT-source test covers the layout fix")
    bundle = _diff_bundle_with_marked_column()
    outpath = tmp_path / "diff_columns"
    with warnings.catch_warnings(record=True) as recorded:
        warnings.simplefilter("always")
        bundle.draw(graph="diff", path=str(outpath))
    messages = " ".join(str(item.message) for item in recorded)
    assert "deleted from cluster" not in messages
    assert "removing empty cluster" not in messages

    root = ElementTree.fromstring(outpath.with_suffix(".svg").read_text(encoding="utf-8"))
    ns = {"svg": "http://www.w3.org/2000/svg"}
    clusters: dict[str, tuple[float, float]] = {}
    nodes: dict[str, float] = {}
    for group in root.iter("{http://www.w3.org/2000/svg}g"):
        title = group.find("svg:title", ns)
        if title is None or title.text is None:
            continue
        xs = [
            float(point.split(",")[0])
            for shape in [
                *group.iter(f"{{{ns['svg']}}}polygon"),
                *group.iter(f"{{{ns['svg']}}}path"),
            ]
            for point in re.findall(
                r"-?\d+(?:\.\d+)?,-?\d+(?:\.\d+)?", shape.get("points") or shape.get("d") or ""
            )
        ]
        if group.get("class") == "cluster" and xs:
            clusters[title.text] = (min(xs), max(xs))
            texts = [text.text for text in group.findall("svg:text", ns)]
            assert any(texts), title.text
        elif group.get("class") == "node" and xs:
            nodes[title.text] = (min(xs) + max(xs)) / 2
    assert {"cluster_clean", "cluster_intervention"} <= set(clusters)
    clean_lo, clean_hi = clusters["cluster_clean"]
    patched_lo, patched_hi = clusters["cluster_intervention"]
    assert clean_hi <= patched_lo or patched_hi <= clean_lo  # two disjoint columns
    clean_nodes = {name: x for name, x in nodes.items() if name.startswith("clean_")}
    patched_nodes = {name: x for name, x in nodes.items() if name.startswith("intervention_")}
    assert clean_nodes and len(clean_nodes) == len(patched_nodes)
    assert all(clean_lo <= x <= clean_hi for x in clean_nodes.values())
    assert all(patched_lo <= x <= patched_hi for x in patched_nodes.values())
