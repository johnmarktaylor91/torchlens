"""Contract tests for the affected-test map in ``test-tiers.json`` (``inner.map``).

The inner-loop selector refuses any changed path that matches no map key, so
every module under ``torchlens/`` must be covered, every listed target must be
an existing test file, and each list must stay short enough for the inner
budget. The map is generated by ``scripts/build_affected_test_map.py``; the
freshness test rebuilds it and compares.

These tests use only pytest and the standard library: no torch import and no
conftest fixtures.
"""

from __future__ import annotations

import fnmatch
import importlib.util
import json
import sys
from pathlib import Path
from types import ModuleType

import pytest

REPO_ROOT = Path(__file__).resolve().parent.parent
TIERS_PATH = REPO_ROOT / "test-tiers.json"
BUILDER_PATH = REPO_ROOT / "scripts" / "build_affected_test_map.py"
MAX_TESTS = 8


def _is_glob(key: str) -> bool:
    """Return whether a map key needs ``fnmatch`` (an exact path does not).

    Parameters
    ----------
    key:
        Map key.

    Returns
    -------
    bool
        True when the key holds a wildcard character.
    """
    return any(ch in key for ch in "*?[")


def _load_map() -> dict[str, list[str]]:
    """Return the committed ``inner.map``.

    Returns
    -------
    dict[str, list[str]]
        Map key (``fnmatch`` pattern) -> list of test file paths.
    """
    data = json.loads(TIERS_PATH.read_text(encoding="utf-8"))
    mapping = data["inner"]["map"]
    assert isinstance(mapping, dict)
    return mapping


def _module_paths() -> list[str]:
    """Return every ``.py`` file under ``torchlens/`` as a repo-relative path.

    Returns
    -------
    list[str]
        Sorted POSIX paths, ``__init__.py`` files included.
    """
    return sorted(
        path.relative_to(REPO_ROOT).as_posix()
        for path in (REPO_ROOT / "torchlens").rglob("*.py")
        if "__pycache__" not in path.parts
    )


def _load_builder() -> ModuleType:
    """Import ``scripts/build_affected_test_map.py`` by path.

    Returns
    -------
    ModuleType
        The builder module.
    """
    spec = importlib.util.spec_from_file_location("_affected_test_map_builder", BUILDER_PATH)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    # ``dataclasses`` resolves string annotations through ``sys.modules``.
    sys.modules[spec.name] = module
    try:
        spec.loader.exec_module(module)
    finally:
        sys.modules.pop(spec.name, None)
    return module


def test_every_torchlens_module_matches_a_key() -> None:
    """Every ``.py`` file under ``torchlens/`` matches at least one map key."""
    keys = list(_load_map())
    exact = {k for k in keys if not _is_glob(k)}
    globs = [k for k in keys if _is_glob(k)]
    modules = _module_paths()
    assert modules, "no modules found under torchlens/"
    unmapped = [
        path
        for path in modules
        if path not in exact and not any(fnmatch.fnmatchcase(path, k) for k in globs)
    ]
    assert not unmapped, f"{len(unmapped)} unmapped modules, e.g. {unmapped[:10]}"


def test_every_listed_target_is_an_existing_test_file() -> None:
    """Every listed path is an existing ``.py`` test file under ``tests/``."""
    tests_root = (REPO_ROOT / "tests").resolve()
    bad: list[str] = []
    for key, targets in _load_map().items():
        assert isinstance(targets, list) and targets, f"{key}: empty or non-list value"
        for target in targets:
            resolved = (REPO_ROOT / target).resolve()
            if not (
                target.startswith("tests/")
                and target.endswith(".py")
                and resolved.is_file()
                and resolved.is_relative_to(tests_root)
            ):
                bad.append(f"{key} -> {target}")
    assert not bad, f"{len(bad)} invalid targets, e.g. {bad[:10]}"


def test_no_list_exceeds_the_cap() -> None:
    """No list is longer than the cap, and lists are sorted without duplicates."""
    for key, targets in _load_map().items():
        assert len(targets) <= MAX_TESTS, f"{key}: {len(targets)} targets"
        assert targets == sorted(set(targets)), f"{key}: unsorted or duplicated targets"


def test_keys_cover_only_torchlens_paths() -> None:
    """Every key is a ``torchlens/`` pattern that matches at least one module."""
    modules = _module_paths()
    module_set = set(modules)
    for key in _load_map():
        assert key.startswith("torchlens/"), key
        if _is_glob(key):
            assert any(fnmatch.fnmatchcase(path, key) for path in modules), f"dead key {key}"
        else:
            assert key in module_set, f"dead key {key}"


@pytest.mark.heavy
def test_committed_map_is_fresh() -> None:
    """A fresh build reproduces the committed ``test-tiers.json`` byte for byte.

    A full build parses every ``torchlens/`` and ``tests/`` file (measured
    about 8-10 s on one core), so the test carries the ``heavy`` (5-20 s) mark.
    """
    builder = _load_builder()
    result = builder.build(REPO_ROOT)
    expected = builder.render(REPO_ROOT, result.mapping, result.tier)
    assert TIERS_PATH.read_text(encoding="utf-8") == expected, (
        "test-tiers.json inner.map or inner.tier is stale; "
        "run python scripts/build_affected_test_map.py"
    )


def test_every_conftest_runs_the_tier() -> None:
    """Every ``conftest.py`` under ``tests/`` is an ``inner.tier`` path (rule ``conftest``)."""
    paths = json.loads(TIERS_PATH.read_text(encoding="utf-8"))["inner"]["tier"]["paths"]
    conftests = sorted(
        path.relative_to(REPO_ROOT).as_posix()
        for path in (REPO_ROOT / "tests").rglob("conftest.py")
    )
    assert conftests
    assert {path: paths.get(path) for path in conftests} == dict.fromkeys(conftests, "conftest")


def test_reviewed_overrides_reach_the_committed_lists() -> None:
    """Every reviewed override test is listed for its module in the committed map."""
    overrides_path = REPO_ROOT / "scripts" / "affected_test_map_overrides.json"
    if not overrides_path.is_file():
        pytest.skip("no reviewed overrides file")
    rows = json.loads(overrides_path.read_text(encoding="utf-8"))["modules"]
    mapping = _load_map()
    missing: list[str] = []
    for module, row in rows.items():
        keys = [
            k for k in mapping if k == module or (_is_glob(k) and fnmatch.fnmatchcase(module, k))
        ]
        listed = {test for key in keys for test in mapping[key]}
        missing.extend(f"{module} -> {test}" for test in row["tests"] if test not in listed)
    assert not missing, missing[:10]
