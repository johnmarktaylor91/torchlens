class HIPT_4K_Staging(nn.Module):
    """HIPT Model (ViT-4K) for encoding non-square images with [256 x 256] patch
    tokens, with [256 x 256] patch tokens encoded via ViT-256 using [16 x 16] patch
    tokens. Reproduces `HIPT_4K.forward` from HIPT_4K/hipt_4k.py verbatim (random-init
    ViT-256/ViT-4K submodules in place of the checkpoint-loaded `get_vit256`/
    `get_vit4k` helpers; single-device forward instead of the repo's 2-GPU split)."""

    def __init__(self, model256, model4k, img_size4k=[224]):
        super().__init__()
        self.model256 = model256
        self.model4k = model4k
        # ViT-4K's positional embedding grid is sized to img_size4k // 16; the
        # forward's feature grid (w_256 x h_256, one ViT-256 [CLS] per 256x256 patch)
        # must match that count, i.e. w_256*16 == img_size4k[0] (see hipt_4k.py's own
        # note: "w_256, h_256" naming is really "# of patch-tokens fed to ViT-4K").

    def prepare_img_tensor(self, img: torch.Tensor, patch_size=256):
        make_divisble = lambda l, ps: l - (l % ps)  # noqa: E731, E741
        b, c, w, h = img.shape
        load_size = make_divisble(w, patch_size), make_divisble(h, patch_size)
        w_256, h_256 = w // patch_size, h // patch_size
        img_new = transforms.CenterCrop(load_size)(img)
        return img_new, w_256, h_256

    def forward(self, x):
        """
        Forward pass of HIPT (given an image tensor x), outputting the [CLS] token
        from ViT-4K.
        1. x is center-cropped such that the W / H is divisible by the patch token
           size in ViT-4K (e.g. - 256 x 256).
        2. x then gets unfolded into a "batch" of [256 x 256] images.
        3. A ViT-256 model extracts the CLS token from each [256 x 256] image in the
           batch.
        4. These batch-of-features are then reshaped into a 2D feature grid (of width
           "w_256" and height "h_256").
        5. This feature grid is then used as the input to ViT-4K, outputting [CLS]_4K.
        """
        batch_256, w_256, h_256 = self.prepare_img_tensor(x)
        batch_256 = batch_256.unfold(2, 256, 256).unfold(3, 256, 256)
        batch_256 = rearrange(batch_256, "b c p1 p2 w h -> (b p1 p2) c w h")

        features_cls256 = []
        for mini_bs in range(0, batch_256.shape[0], 256):
            minibatch_256 = batch_256[mini_bs : mini_bs + 256]
            features_cls256.append(self.model256(minibatch_256))

        features_cls256 = torch.vstack(features_cls256)
        features_cls256 = (
            features_cls256.reshape(w_256, h_256, 384)
            .transpose(0, 1)
            .transpose(0, 2)
            .unsqueeze(dim=0)
        )
        features_cls4k = self.model4k.forward(features_cls256)
        return features_cls4k


def build_hipt4k():
    # Real repo defaults (get_vit256/get_vit4k in hipt_model_utils.py): ViT-256 is
    # `vit_small(patch_size=16, num_classes=0)`; ViT-4K is `vit4k_xs(num_classes=0)`
    # (input_embed_dim=384 matches ViT-256's embed_dim). img_size4k=[256] means ViT-4K
    # expects a 16x16 feature-token grid (256 // 16), i.e. a 256x256-patch input image
    # of 4096x4096 pixels in the real pipeline; scaled down here to keep the trace fast
    # while preserving the exact hierarchical composition.
    model256 = vit_small(patch_size=16, num_classes=0)
    model4k = vit4k_xs(img_size=[256], num_classes=0)
    model256.eval()
    model4k.eval()
    model = HIPT_4K_Staging(model256, model4k, img_size4k=[256])
    model.eval()
    return model


