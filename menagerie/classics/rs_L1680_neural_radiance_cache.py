# (original framework: C++/CUDA custom kernels via the `tinycudann` PyTorch extension)
#
# "Real-time Neural Radiance Caching for Path Tracing" (Muller, Rousselle, Novak, Keller;
# SIGGRAPH 2021 / ACM TOG). NVIDIA's own NRC library releases (NVIDIA-RTX/NRC) and the
# reference `tinycudann` bindings (bindings/torch/tinycudann/modules.py) both hard-require
# a compiled custom-CUDA extension (`tinycudann_bindings`) built for the local GPU compute
# capability -- `tinycudann/__init__.py` raises `EnvironmentError` at import time if that
# extension is missing, so it cannot be installed/vendored/run in this base env (no compiler
# toolchain, no per-arch prebuilt wheels on PyPI). A real, public, pure-Python *usage* of
# NRC exists at USharma002/py-neural-path-guiding (networks/nrc.py, class
# `NeuralRadianceCache`) -- it wires up a `tcnn.NetworkWithInputEncoding` with the exact
# encoding/network config transcribed below (Composite[HashGrid, SphericalHarmonics x2,
# OneBlob] -> FullyFusedMLP), but it still imports `tinycudann` directly and thus hits the
# same hard CUDA-extension wall. Per the FAITHFUL PORT rung, we transcribe the actual
# encoding math and network shape from the real tiny-cuda-nn CUDA source (each op below is
# a direct translation, not a guess from the paper):
#   - `include/tiny-cuda-nn/encodings/grid.h` (HashGrid): per-level N-linear interpolation
#     over either a dense or a spatially-hashed feature grid; grid_index/grid_scale exactly
#     as in `common_device.h` (default HashType::CoherentPrime lcg_hash with the real prime
#     factor table).
#   - `include/tiny-cuda-nn/common_device.h`'s `sh_enc` (SphericalHarmonicsEncoding):
#     real-valued spherical-harmonic basis polynomials up to degree 4 (16 outputs),
#     verbatim closed-form coefficients from the CUDA source (generated by NVIDIA's own
#     scripts/gen_sh.py from the Sloan SH recurrence relations).
#   - `include/tiny-cuda-nn/encodings/oneblob.h` (OneBlobEncoding): per-scalar quartic-CDF
#     soft-binning (`quartic_cdf`), verbatim from `common_device.h`.
#   - `include/tiny-cuda-nn/networks/fully_fused_mlp.h`: architecturally a uniform-width
#     `n_hidden_layers`-deep MLP with a fixed activation/output_activation (`FullyFusedMLP`
#     is a CUDA kernel-fusion optimization of exactly this MLP topology, not a distinct
#     architecture -- the tcnn docs describe it as such); reproduced here as plain
#     `nn.Linear` + `nn.ReLU` layers matching n_neurons=64, n_hidden_layers=4 from the real
#     `nrc.py` config, output_activation="None".
# The wrapping module (`NeuralRadianceCache`: bbox-normalize position -> pack
# pos/view/normal/roughness -> encode -> FullyFusedMLP -> softplus) mirrors
# `py-neural-path-guiding`'s `networks/nrc.py` forward/query pipeline verbatim, with the
# `tcnn.NetworkWithInputEncoding` call replaced by the torch modules below.
