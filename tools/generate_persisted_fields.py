"""Write ``docs/maintainers/PERSISTED_FIELDS.md`` from the v11 writer contract.

The table lists every persisted record field of the current saved format: its stored key,
owning record class, field policy, tier and the public spelling the glossary gives it (a
Trace group leaf ``_<group>_<leaf>`` reads as ``Trace.<group>.<leaf>``; a key with no public
spelling is private storage). ``--check`` exits 1 when the committed document differs from
the contract.

usage: python tools/generate_persisted_fields.py [--check]
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTRACT = ROOT / "torchlens" / "schemas" / "writer_contract_v11.json"
GLOSSARY = ROOT / "docs" / "reference" / "glossary.md"
TARGET = ROOT / "docs" / "maintainers" / "PERSISTED_FIELDS.md"
GROUPS = ("provenance", "options", "cost", "source", "health", "graph", "autograd")


def _public_spelling(owner: str, key: str, glossary: str) -> str:
    """Return the glossary spelling of ``owner.key`` or ``private``."""

    if owner == "Trace":
        match = re.match(rf"_({'|'.join(GROUPS)})_(\w+)$", key)
        if match:
            group, leaf = match.group(1), match.group(2)
            candidate = f"Trace.{group}.{leaf}"
            member = f"Trace{group.capitalize()}.{leaf}"
            if candidate in glossary or member in glossary:
                return f"`{candidate}`"
            return f"`{candidate}` (stored key only; no view member)"
    if key.startswith("_"):
        return "private"
    candidate = f"{owner}.{key}"
    if candidate in glossary or f"`{key}`" in glossary or f"`{key}=`" in glossary:
        return f"`{candidate}`"
    return f"`{candidate}` (not in the glossary)"


def render() -> str:
    """Render the document text from the contract and the glossary."""

    contract = json.loads(CONTRACT.read_text(encoding="utf-8"))["contract"]
    glossary = GLOSSARY.read_text(encoding="utf-8")
    records = contract["record_contracts"]
    lines = [
        "# Persisted fields of the saved format (tlspec v11)",
        "",
        "Generated by `tools/generate_persisted_fields.py` from "
        "`torchlens/schemas/writer_contract_v11.json`; do not edit by hand. One row per persisted",
        "field: the stored key, the record that owns it, its field policy (`keep` is written and",
        "read back, `drop` is session-only and never written, `blob_recursive` is written as a",
        "recursive blob), its tier, and the public spelling the glossary gives it. `private` keys",
        "are storage behind an accessor and have no public spelling.",
        "",
        f"Reader floor: tlspec {contract['min_tlspec_version']} "
        f"(torchlens {contract['min_torchlens_version']}).",
        "",
    ]
    total = 0
    for record_key in sorted(records):
        record = records[record_key]
        owner = record["class"].rsplit(".", 1)[-1]
        policies = record["field_policies"]
        tiers = record.get("field_tiers", {})
        persisted = sorted(record["persisted_field_names"])
        lines += [
            f"## `{record_key}` ({owner}, {len(persisted)} persisted of {len(policies)} fields)",
            "",
            "| key | policy | tier | public spelling |",
            "| --- | --- | --- | --- |",
        ]
        for key in sorted(policies):
            policy = policies[key]
            if key not in persisted and policy != "drop":
                continue
            if key not in persisted and policy == "drop":
                continue
            total += 1
            lines.append(
                f"| `{key}` | {policy} | {tiers.get(key, '')} | "
                f"{_public_spelling(owner, key, glossary)} |"
            )
        dropped = sorted(k for k, p in policies.items() if p == "drop")
        if dropped:
            lines += ["", f"Session-only (`drop`): {', '.join(f'`{k}`' for k in dropped)}."]
        lines.append("")
    lines.insert(10, f"Persisted fields in total: {total}.")
    lines.insert(11, "")
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv: list[str]) -> int:
    """Write or check the document."""

    text = render()
    if "--check" in argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print(f"{TARGET.relative_to(ROOT)} is stale; run tools/generate_persisted_fields.py")
            return 1
        print(f"{TARGET.relative_to(ROOT)} is current")
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
