"""Generate ``docs/maintainers/where.md``, the "where does X live" index.

One command: ``python tools/docs/where_index.py``. It walks ``torchlens/``, reads the
first docstring line of every package ``__init__.py`` and every module with
``ast`` (nothing is imported), and writes one table per package: module, first
docstring line, line count. ``--check`` exits 1 when the committed page differs
from what the walk would write, so a currency check can call it after a module
moves. Package moves need no edit here: the walk follows the tree.
"""

from __future__ import annotations

import argparse
import ast
import sys
from dataclasses import dataclass
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
PACKAGE_ROOT = REPO / "torchlens"
OUTPUT = REPO / "docs" / "maintainers" / "where.md"
COMMAND = "python tools/docs/where_index.py"
SUMMARY_LIMIT = 140
NO_DOCSTRING = "(no docstring)"
SKIP_DIRS = {"__pycache__"}


@dataclass(frozen=True)
class ModuleRow:
    """One module of the index."""

    name: str
    summary: str
    lines: int


@dataclass(frozen=True)
class PackageRows:
    """One package of the index: its own summary and its direct modules."""

    dotted: str
    summary: str
    modules: tuple[ModuleRow, ...]

    @property
    def lines(self) -> int:
        return sum(row.lines for row in self.modules)


def first_docstring_line(path: Path) -> str:
    """Return the first non-empty docstring line of ``path``, or a placeholder."""

    source = path.read_text(encoding="utf-8")
    try:
        tree = ast.parse(source, filename=str(path))
    except SyntaxError as exc:
        return f"(syntax error at line {exc.lineno})"
    docstring = ast.get_docstring(tree, clean=True)
    if not docstring:
        return NO_DOCSTRING
    for line in docstring.splitlines():
        text = line.strip()
        if text:
            return text
    return NO_DOCSTRING


def line_count(path: Path) -> int:
    """Return the number of lines in ``path``."""

    with path.open("rb") as handle:
        return sum(1 for _ in handle)


def _escape(text: str) -> str:
    """Make ``text`` safe inside a Markdown table cell, clipped to one line."""

    cell = text.replace("|", "\\|").replace("`", "'")
    if len(cell) > SUMMARY_LIMIT:
        cell = cell[: SUMMARY_LIMIT - 3].rstrip() + "..."
    return cell


def _dotted(package_dir: Path) -> str:
    relative = package_dir.relative_to(PACKAGE_ROOT.parent)
    return ".".join(relative.parts)


def collect_package(package_dir: Path) -> PackageRows:
    """Index one package directory: its ``__init__`` summary and direct modules."""

    init = package_dir / "__init__.py"
    rows = [ModuleRow("__init__", first_docstring_line(init), line_count(init))]
    for module in sorted(package_dir.glob("*.py")):
        if module.name == "__init__.py":
            continue
        rows.append(ModuleRow(module.stem, first_docstring_line(module), line_count(module)))
    return PackageRows(_dotted(package_dir), first_docstring_line(init), tuple(rows))


def collect_packages(root: Path = PACKAGE_ROOT) -> list[PackageRows]:
    """Walk ``root`` and return every package (a directory with ``__init__.py``)."""

    packages: list[PackageRows] = []
    for package_dir in sorted(root.rglob("*")):
        if not package_dir.is_dir() or package_dir.name in SKIP_DIRS:
            continue
        if any(part in SKIP_DIRS for part in package_dir.relative_to(root).parts):
            continue
        if (package_dir / "__init__.py").is_file():
            packages.append(collect_package(package_dir))
    return [collect_package(root), *packages]


def _render_package(package: PackageRows) -> list[str]:
    out = [
        f"### `{package.dotted}`",
        "",
        f"{_escape(package.summary)} ({len(package.modules)} modules, {package.lines} lines)",
        "",
        "| Module | What it holds | Lines |",
        "| --- | --- | ---: |",
    ]
    for row in package.modules:
        out.append(f"| `{row.name}` | {_escape(row.summary)} | {row.lines} |")
    out.append("")
    return out


def render(packages: list[PackageRows]) -> str:
    """Render the whole index page as Markdown."""

    total_modules = sum(len(package.modules) for package in packages)
    total_lines = sum(package.lines for package in packages)
    missing = sum(
        1 for package in packages for row in package.modules if row.summary == NO_DOCSTRING
    )
    out = [
        "# Where does X live",
        "",
        f"Generated by `{COMMAND}`; do not edit by hand. Rerun it after adding, moving or",
        "renaming a module and commit the result. Each row is a module's first docstring line,",
        "so a wrong row is fixed in the module's docstring, not here. The index follows the tree:",
        "a package move shows up on the next run with no edit to the generator.",
        "",
        f"{len(packages)} packages, {total_modules} modules, {total_lines} lines, "
        f"{missing} modules without a docstring.",
        "",
        "## Packages",
        "",
        "| Package | What it holds | Modules | Lines |",
        "| --- | --- | ---: | ---: |",
    ]
    for package in packages:
        out.append(
            f"| `{package.dotted}` | {_escape(package.summary)} | "
            f"{len(package.modules)} | {package.lines} |"
        )
    out.extend(["", "## Modules by package", ""])
    for package in packages:
        out.extend(_render_package(package))
    return "\n".join(out).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 when the committed page differs from the current tree",
    )
    args = parser.parse_args(argv)
    text = render(collect_packages())
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else ""
        if current != text:
            print(f"{OUTPUT.relative_to(REPO)} is stale; run `{COMMAND}`", file=sys.stderr)
            return 1
        print(f"{OUTPUT.relative_to(REPO)} is current")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
