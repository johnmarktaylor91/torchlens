"""Summary performance benchmark (F08; summary memo item 16 / 3.12).

Measures the four phases SEPARATELY -- capture (wrapped forward), the
postprocess pipeline, render, and cleanup -- against a plain uninstrumented
forward (min-of-N), and regenerates the published benchmarks page
(``docs/benchmarks/summary_performance.md``). The page is the forcing
function ("we will not publish 63x"): the ratio feeds the memo's F1
engine-floor trigger (a second capture engine goes to JMT only if the
optimized single-engine summary stays above ~5x a plain forward).

Run:  python tools/benchmark_summary.py [--models resnet18,toy] [--repeats 5]
"""

from __future__ import annotations

import argparse
import sys
import time
from collections.abc import Callable
from pathlib import Path
from typing import Any

import torch
from torch import nn

_PAGE = Path(__file__).resolve().parent.parent / "docs" / "benchmarks" / "summary_performance.md"


class _Toy(nn.Module):
    """Small conv stack for the cheap benchmark row."""

    def __init__(self) -> None:
        """Conv/relu/linear toy."""

        super().__init__()
        self.conv = nn.Conv2d(3, 8, 3, padding=1)
        self.fc = nn.Linear(8 * 32 * 32, 10)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        """conv -> relu -> flatten -> fc."""

        return self.fc(torch.flatten(torch.relu(self.conv(x)), 1))


def _model_catalog() -> dict[str, Callable[[], tuple[nn.Module, Any]]]:
    """Benchmark model constructors (zero network)."""

    def toy() -> tuple[nn.Module, Any]:
        """The cheap row."""

        return _Toy().eval(), torch.randn(1, 3, 32, 32)

    def resnet18() -> tuple[nn.Module, Any]:
        """The real-CNN row."""

        from torchvision import models

        return models.resnet18(weights=None).eval(), torch.randn(1, 3, 224, 224)

    def gpt2() -> tuple[nn.Module, Any]:
        """The real-LM row (config-built, zero network)."""

        from transformers import GPT2Config, GPT2LMHeadModel

        return GPT2LMHeadModel(GPT2Config()).eval(), torch.arange(16).unsqueeze(0)

    return {"toy": toy, "resnet18": resnet18, "gpt2": gpt2}


def _min_of(callable_: Callable[[], Any], repeats: int) -> float:
    """Best-of-N wall time in seconds."""

    best = float("inf")
    for _ in range(repeats):
        start = time.perf_counter()
        callable_()
        best = min(best, time.perf_counter() - start)
    return best


def benchmark_model(name: str, repeats: int) -> dict[str, float]:
    """Measure the four phases + the plain forward for one model."""

    import torchlens as tl
    from torchlens import postprocess as pp_module

    model, example = _model_catalog()[name]()
    with torch.no_grad():
        forward_s = _min_of(lambda: model(example), repeats)

    postprocess_s = 0.0
    original_postprocess = pp_module.postprocess

    def timed_postprocess(*args: Any, **kwargs: Any) -> Any:
        """Time the postprocess pipeline inside the capture."""

        nonlocal postprocess_s
        start = time.perf_counter()
        try:
            return original_postprocess(*args, **kwargs)
        finally:
            postprocess_s = time.perf_counter() - start

    trace = None

    def run_capture() -> None:
        """One full metadata-only capture."""

        nonlocal trace
        if trace is not None:
            trace.cleanup()
        trace = tl.trace(model, example)

    pp_module.postprocess = timed_postprocess  # type: ignore[assignment]
    try:
        capture_s = _min_of(run_capture, max(repeats // 2, 1))
    finally:
        pp_module.postprocess = original_postprocess  # type: ignore[assignment]
    assert trace is not None

    render_s = _min_of(lambda: trace.summary(), max(repeats // 2, 1))
    start = time.perf_counter()
    trace.cleanup()
    cleanup_s = time.perf_counter() - start
    tl.release_model(model)
    total_s = capture_s + render_s + cleanup_s
    return {
        "forward_s": forward_s,
        "capture_s": capture_s,
        "postprocess_s": postprocess_s,
        "render_s": render_s,
        "cleanup_s": cleanup_s,
        "total_s": total_s,
        "ratio": total_s / forward_s if forward_s else float("inf"),
        "postprocess_share": postprocess_s / capture_s if capture_s else 0.0,
    }


def write_page(rows: dict[str, dict[str, float]]) -> None:
    """Regenerate the published benchmarks page from measured rows."""

    lines = [
        "# Summary performance (regenerated by tools/benchmark_summary.py)",
        "",
        "One-call `tl.summary(model, x)` cost decomposed against a plain",
        "uninstrumented forward (min-of-N, CPU, single process). The RATIO",
        "column is the published figure the summary memo's F1 engine-floor",
        "trigger reads: a second capture engine is considered only if the",
        "optimized single-engine summary stays above ~5x a plain forward.",
        "",
        "| model | forward | capture | postprocess (in capture) | render | cleanup | summary total | ratio | postprocess share |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for name, row in rows.items():
        lines.append(
            f"| {name} | {row['forward_s'] * 1000:.1f} ms | {row['capture_s'] * 1000:.1f} ms "
            f"| {row['postprocess_s'] * 1000:.1f} ms | {row['render_s'] * 1000:.1f} ms "
            f"| {row['cleanup_s'] * 1000:.1f} ms | {row['total_s'] * 1000:.1f} ms "
            f"| {row['ratio']:.1f}x | {row['postprocess_share'] * 100:.0f}% |"
        )
    lines += [
        "",
        "Notes:",
        "",
        "- `postprocess` is measured INSIDE `capture` (the wrapped forward plus",
        "  the 26-step pipeline); its share is the summary-scoped optimization",
        "  target the summary memo measured at ~64% of capture cost on the",
        "  pre-speedening baseline (f74e4a9e). The post-speedening share is",
        "  what THIS page reports.",
        "- `render` is the rebuilt view ladder + hairline renderer (F08).",
        "- Numbers vary by host AND by concurrent load (both the plain forward",
        "  and the capture inflate together under load, compressing the ratio",
        "  less than either absolute); regenerate on a quiet host with",
        "  `python tools/benchmark_summary.py` and commit the page.",
        "- F1 disposition (memo 3.12): a second hook-based capture engine goes",
        "  to JMT only if the optimized single-engine ratio stays above ~5x.",
        "",
    ]
    _PAGE.parent.mkdir(parents=True, exist_ok=True)
    _PAGE.write_text("\n".join(lines))


def main(argv: list[str]) -> int:
    """CLI entry: benchmark the requested models and rewrite the page."""

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--models", default="toy,resnet18,gpt2")
    parser.add_argument("--repeats", type=int, default=5)
    args = parser.parse_args(argv)
    rows: dict[str, dict[str, float]] = {}
    for name in args.models.split(","):
        name = name.strip()
        print(f"== benchmarking {name}", file=sys.stderr)
        rows[name] = benchmark_model(name, args.repeats)
        print(rows[name], file=sys.stderr)
    write_page(rows)
    print(f"wrote {_PAGE}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
